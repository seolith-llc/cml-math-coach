export const APP_NAME = 'Puzzle Trail';
/** The date the current terms and privacy policy took effect (YYYY-MM-DD). */
export const TERMS_VERSION = '2026-11-18';
/** Access lasts this many days after accepting; then the terms are shown again and must be accepted again. */
export const ACCEPT_DAYS = 30;

export interface Acceptance {
  version: string;
  at: number;
}

/** Whether the terms must be (re)accepted now: never accepted, a newer version, or more than 30 days ago. */
export function termsDue(a: Acceptance | null | undefined, now = Date.now()): boolean {
  if (!a || a.version !== TERMS_VERSION) return true;
  return now - a.at >= ACCEPT_DAYS * 86_400_000 || a.at > now + 86_400_000;
}

/** Days left before the terms must be accepted again (0 when due). */
export function daysLeft(a: Acceptance | null | undefined, now = Date.now()): number {
  if (termsDue(a, now)) return 0;
  return Math.max(0, Math.ceil((a!.at + ACCEPT_DAYS * 86_400_000 - now) / 86_400_000));
}

